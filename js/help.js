document.addEventListener('click', e => {
  const g = e.target.dataset?.go;
  if (g) document.getElementById(g)?.scrollIntoView({ behavior: 'smooth' });
});

document.addEventListener('click', e => {
  if (e.target.id === 'bk') {
    S.tab = '';
    render();
  }
});
