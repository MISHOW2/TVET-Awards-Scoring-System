// The topic to show: the one chosen, else the one for this person's role.
function helpTopic() {
  const own = S.role === 'auditor' ? 'auditors' : S.role === 'admin' ? 'admin' : 'judges';
  return HELP_TOPICS.find(t => t[0] === S.helpTopic) ? S.helpTopic : own;
}

function help() {
  const cur = helpTopic(),
    topic = HELP_TOPICS.find(t => t[0] === cur);
  return `<h1>Help</h1><p class="sub">Choose a topic. Everything is saved to a shared Google Sheet, so every person sees the same up-to-date information.</p>
  <div class="row" style="margin:14px 0" role="group" aria-label="Help topics">${HELP_TOPICS.map(
    t =>
      `<button class="btn chipbtn ${t[0] === cur ? 'dark' : ''}" data-help="${t[0]}" aria-pressed="${t[0] === cur}">${t[1]}</button>`,
  ).join('')}</div>
  <div style="max-width:860px">${topic[2]()}</div>
  ${S.role === 'admin' || S.role === 'auditor' ? '' : '<p><button class="lnk" id="bk">← Back</button></p>'}`;
}

document.addEventListener('click', e => {
  const b = e.target.closest && e.target.closest('[data-help]');
  if (b) {
    S.helpTopic = b.dataset.help;
    render();
  }
  if (e.target.id === 'bk') {
    S.tab = '';
    S.helpTopic = null;
    render();
  }
});
